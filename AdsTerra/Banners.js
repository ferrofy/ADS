function Banner_728x90() {
    var Container = document.createElement("div");
    Container.style.width = "728px";
    Container.style.maxWidth = "100%";
    Container.style.margin = "10px auto";

    var Frame = document.createElement("iframe");
    Frame.width = "728";
    Frame.height = "90";
    Frame.style.width = "100%";
    Frame.style.height = "90px";
    Frame.style.border = "0";
    Frame.setAttribute("scrolling", "no");
    Frame.setAttribute("title", "Adsterra banner, 728 by 90");

    Container.appendChild(Frame);

    Frame.srcdoc = `
        <!DOCTYPE html>
        <html>
        <head>
            <meta name="viewport" content="width=device-width, initial-scale=1">
        </head>
        <body style="margin:0;padding:0">
            <script>
                window.atOptions = {
                    key: "fa5056900c1366811b13cfffc43d6f6e",
                    format: "iframe",
                    height: 90,
                    width: 728,
                    params: {}
                };
            <\/script>
            <script src="https://www.highrevenueformat.com/fa5056900c1366811b13cfffc43d6f6e/invoke.js"><\/script>
        </body>
        </html>
    `;

    return Container;
}

